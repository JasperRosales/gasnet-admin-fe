import { useCallback, useEffect, useRef, useState } from 'react'
import { getInsights, geminiReady } from '../lib/gemini'
import { useInView } from '../lib/lazyData'

const DEBOUNCE_MS = 800 // wait for filters to settle before asking Gemini

const ago = (time) => {
  const mins = Math.round((Date.now() - time) / 60000)
  if (mins < 1) return 'just now'
  if (mins < 60) return `${mins} min ago`
  return `${Math.round(mins / 60)} h ago`
}

// summary: plain JSON of the numbers on screen; hasData: false skips the API call
// ready: the page's numbers are fully loaded; autoKey: the page's filters. Insights are made by
// themselves only when the filters change (or the page loads), not on every live update of the
// numbers (each POS sale would cost a Gemini call); after a live update a note offers Refresh.
export default function AiInsights({ summary, hasData, ready = true, autoKey = '' }) {
  const [state, setState] = useState({ status: 'idle', items: [], error: '', savedAt: 0, fromCache: false, usedText: '' })
  const runId = useRef(0)
  // Gemini is asked only once this section is scrolled into view
  const [boxRef, seen] = useInView()
  const summaryText = JSON.stringify(summary)

  const load = useCallback(async (force = false) => {
    const id = ++runId.current
    setState((s) => ({ ...s, status: 'loading', error: '' }))
    try {
      const r = await getInsights(JSON.parse(summaryText), { force })
      if (id !== runId.current) return // a newer request replaced this one
      setState({ status: 'done', items: r.value, error: '', savedAt: r.savedAt, fromCache: r.fromCache, usedText: summaryText })
    } catch (e) {
      if (id !== runId.current) return
      setState((s) => ({ ...s, status: 'error', error: e.message }))
    }
  }, [summaryText])

  // the newest load, so the effect below does not run again on every change of the numbers
  const loadRef = useRef(load)
  useEffect(() => {
    loadRef.current = load
  })

  useEffect(() => {
    if (!geminiReady || !hasData || !seen || !ready) return
    const t = setTimeout(() => loadRef.current(false), DEBOUNCE_MS)
    return () => clearTimeout(t)
  }, [autoKey, ready, hasData, seen])

  // the numbers changed (live update) since these insights were made
  const outdated = state.status === 'done' && state.usedText && state.usedText !== summaryText

  let note = ''
  if (!geminiReady) note = 'AI insights are turned off (VITE_AI_INSIGHTS=off).'
  else if (!hasData) note = 'Not enough data yet. Insights appear once there are accepted orders or stock.'
  else if (state.status === 'error') note = `Could not load insights: ${state.error}`

  return (
    <div ref={boxRef}>
      <div className="mb-1 flex items-center justify-between gap-2">
        <h3 className="m-0 text-lg">AI Insights</h3>
        {geminiReady && hasData && (
          <button
            type="button"
            className="rounded-lg border border-(color:--border) bg-white px-3 py-1 text-[14px] text-brand-pine hover:bg-brand-light disabled:opacity-50"
            onClick={() => load(true)}
            disabled={state.status === 'loading'}
          >
            {state.status === 'loading' ? 'Thinking…' : 'Refresh'}
          </button>
        )}
      </div>
      <p className="mb-4 text-[14px] text-gray-500">
        Generated by Gemini from this page&apos;s numbers and a 4-week sales forecast
        {state.savedAt > 0 && ` · ${state.fromCache ? 'cached' : 'new'}, ${ago(state.savedAt)}`}
        {outdated && (
          <span className="text-amber-700"> · new sales since then, press Refresh to update</span>
        )}
      </p>

      {note && <p className="text-[14px] text-gray-600">{note}</p>}

      {!note && (
        <div className="grid grid-cols-3 gap-4 max-[1100px]:grid-cols-2 max-[640px]:grid-cols-1">
          {state.status === 'loading' && state.items.length === 0
            ? [0, 1, 2, 3, 4, 5].map((i) => (
                <div key={i} className="h-28 animate-pulse rounded-xl border border-(color:--border) bg-gray-50" />
              ))
            : state.items.map((insight) => {
                const forecast = insight.kind === 'prediction'
                return (
                  <div
                    key={insight.title}
                    className={`rounded-xl border p-4 ${forecast ? 'border-amber-200 bg-amber-50/60' : 'border-(color:--border) bg-white'} ${state.status === 'loading' ? 'opacity-50' : ''}`}
                  >
                    <div className="flex items-start justify-between gap-2">
                      <span className="text-[14px] font-semibold text-brand-pine">{insight.title}</span>
                      <span
                        className={`shrink-0 rounded-full px-2 py-0.5 text-[12px] font-medium ${forecast ? 'bg-amber-100 text-amber-800' : 'bg-brand-light text-brand-pine'}`}
                      >
                        {forecast ? 'Forecast' : 'Insight'}
                      </span>
                    </div>
                    <p className="mb-0 mt-1 text-[14px] text-gray-700">{insight.text}</p>
                  </div>
                )
              })}
        </div>
      )}
    </div>
  )
}
